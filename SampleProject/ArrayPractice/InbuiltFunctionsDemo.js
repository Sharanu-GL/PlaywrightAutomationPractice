// In-Built Functions in Array
// push : It adds elements at last
let s1=[10,20,30,40,50]
console.log(s1)
s1.push("Lavendar")
s1.push("Morning Glory") // [ 10, 20, 30, 40, 50, 'Lavendar', 'Morning Glory' ]
console.log(s1)
console.log("-------------------")
// pop : It removes elements from last
let s2=["Sunflower","Lotus","Tulip","Lilly","Aster","Lavendar", 'Morning Glory']
console.log(s2)
s2.pop()
console.log(s2)
s2.pop()
console.log(s2)
console.log("-------------------")
// unshift : It adds elements from first position
let s3=[2,4,6,8,10,12]
console.log(s3)
s3.unshift(20)
console.log(s3)
s3.unshift(30)
console.log(s3)
console.log("-------------------")
// shift : It removes Elements from First Position
let s4=[2,4,6,8,10,12]
console.log(s4)
s4.shift()
console.log(s4)
s4.shift()
console.log(s4)
console.log("-------------------")